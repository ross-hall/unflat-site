// Builds plugin-snippet/dist/verifyLicence.js: a single self-contained file (tweetnacl inlined)
// for plugins without a bundler. It defines a global `UnflatLicence` with verifyLicence and PUBLIC_KEY.
//   npm run build:plugin

import { build } from "esbuild";

await build({
  entryPoints: ["plugin-snippet/verifyLicence.ts"],
  outfile: "plugin-snippet/dist/verifyLicence.js",
  bundle: true,
  format: "iife",
  globalName: "UnflatLicence",
  platform: "browser", // tweetnacl's "browser" field drops its optional Node crypto import
  target: "es2017",
  minify: true,
  legalComments: "inline",
  banner: { js: "// Unflat licence verifier. Generated by scripts/build-plugin-snippet.mjs; edit verifyLicence.ts instead." },
});
console.log("Wrote plugin-snippet/dist/verifyLicence.js");
